#!/usr/bin/env python3
"""Profile the raw datasets (read-only) and emit docs/dataset-profile.md + data/manifest.json.

Never modifies source files — they are immutable evidence. All numbers here are computed
from the actual files on disk, not hand-written.

Usage: python scripts/profile_datasets.py [--raw data/raw]
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import re
from collections import Counter
from datetime import datetime
from pathlib import Path

DATE_ISO = re.compile(r"^\d{4}-\d{2}-\d{2}$")
INT_RE = re.compile(r"^-?\d+$")
FLOAT_RE = re.compile(r"^-?\d+(\.\d+)?$")


def infer_type(values: list[str]) -> str:
    non_null = [v for v in values if v != ""]
    if not non_null:
        return "empty"
    if all(DATE_ISO.match(v) for v in non_null):
        return "date(iso)"
    if all(INT_RE.match(v) for v in non_null):
        return "int"
    if all(FLOAT_RE.match(v) for v in non_null):
        return "float"
    if any(DATE_ISO.match(v) for v in non_null):
        return "date(mixed/dirty)"
    if any(FLOAT_RE.match(v) for v in non_null):
        return "numeric(mixed/dirty)"
    # small enum?
    uniq = set(non_null)
    if len(uniq) <= 12:
        return f"enum({len(uniq)})"
    return "string"


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    h.update(p.read_bytes())
    return h.hexdigest()


def profile_csv(path: Path) -> dict:
    with path.open(newline="") as f:
        reader = csv.DictReader(f)
        cols = reader.fieldnames or []
        rows = list(reader)
    col_stats = []
    for c in cols:
        vals = [r[c] for r in rows]
        non_null = [v for v in vals if v != ""]
        counter = Counter(non_null)
        examples = [v for v, _ in counter.most_common(3)]
        col_stats.append(
            {
                "column": c,
                "type": infer_type(vals),
                "nulls": sum(1 for v in vals if v == ""),
                "unique": len(set(non_null)),
                "examples": examples,
            }
        )
    # duplicate rows (full-row)
    seen: Counter = Counter(tuple(r.values()) for r in rows)
    dup_rows = sum(c - 1 for c in seen.values() if c > 1)
    return {
        "file": path.name,
        "rows": len(rows),
        "columns": len(cols),
        "duplicate_full_rows": dup_rows,
        "sha256": sha256_file(path),
        "bytes": path.stat().st_size,
        "col_stats": col_stats,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--raw", default="data/raw")
    args = ap.parse_args()
    raw = Path(args.raw)

    csv_files = sorted(raw.glob("*.csv"))
    profiles = [profile_csv(p) for p in csv_files]

    # manifest.json (evidence fingerprint)
    manifest = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "raw_dir": str(raw),
        "files": [
            {"filename": p["file"], "sha256": p["sha256"], "bytes": p["bytes"], "rows": p["rows"]}
            for p in profiles
        ],
    }
    # validation_rules.json is not a CSV, so add it explicitly (CSVs already globbed above).
    for extra in ("validation_rules.json",):
        ep = raw / extra
        if ep.exists():
            manifest["files"].append(
                {"filename": extra, "sha256": sha256_file(ep), "bytes": ep.stat().st_size,
                 "rows": None}
            )
    Path("data/manifest.json").write_text(json.dumps(manifest, indent=2))

    # dataset-profile.md
    out = ["# Dataset Profile", "",
           "> Auto-generated by `scripts/profile_datasets.py` from the actual files in `data/raw/`.",
           "> Source: **synthetic bootstrap** (organizer real dataset not shipped; see dataset-profile note).",
           f"> Generated: {manifest['generated_at']}", ""]
    for p in profiles:
        out.append(f"## {p['file']}")
        out.append("")
        out.append(f"- Rows: **{p['rows']}** · Columns: **{p['columns']}** · "
                   f"Full-row duplicates: {p['duplicate_full_rows']} · Bytes: {p['bytes']}")
        out.append(f"- SHA-256: `{p['sha256']}`")
        out.append("")
        out.append("| Column | Inferred type | Nulls | Unique | Example values |")
        out.append("|---|---|---|---|---|")
        for cs in p["col_stats"]:
            ex = ", ".join(str(e) for e in cs["examples"])
            out.append(f"| {cs['column']} | {cs['type']} | {cs['nulls']} | {cs['unique']} | {ex} |")
        out.append("")
    Path("docs/dataset-profile.md").write_text("\n".join(out))

    print(json.dumps({"profiled": [p["file"] for p in profiles],
                      "manifest": "data/manifest.json",
                      "profile_doc": "docs/dataset-profile.md"}, indent=2))


if __name__ == "__main__":
    main()
